function setupTopicNavigation() {
  const panel = $("#detail-panel");
  const contents = $$(".detail-panel-content");
  if (!panel || !contents.length) return;

  function closeAllDetails() {
    contents.forEach((content) => {
      content.hidden = true;
      content.classList.remove("detail-content-active");
    });
    $$(".topic-icon-card.is-selected").forEach((card) => card.classList.remove("is-selected"));
  }

  $$(".topic-icon-card").forEach((card) => {
    card.addEventListener("click", (event) => {
      const selector = card.getAttribute("href");
      if (!selector || !selector.startsWith("#")) return;
      const target = document.querySelector(selector);
      if (!target) return;
      event.preventDefault();

      const key = card.dataset.sectionFlag;

      // The programme is a dedicated section that appears before
      // “Tutto ciò che devi sapere”. Clicking its card simply brings
      // that section into view instead of opening a second copy below.
      if (key === "schedule") {
        closeAllDetails();
        panel.hidden = true;
        $$(".topic-icon-card.is-selected").forEach((el) => el.classList.remove("is-selected"));
        card.classList.add("is-selected");
        history.replaceState(null, "", "#program");
        window.setTimeout(() => {
          target.scrollIntoView({ behavior: "smooth", block: "center", inline: "nearest" });
        }, 40);
        return;
      }

      if (!key) return;
      closeAllDetails();
      target.hidden = false;
      target.classList.add("detail-content-active");
      card.classList.add("is-selected");
      panel.hidden = false;
      panel.classList.add("is-open");

      history.replaceState(null, "", selector);

      // Bring the opened content into the visual center of the page.
      window.setTimeout(() => {
        panel.scrollIntoView({ behavior: "smooth", block: "center", inline: "nearest" });
      }, 40);
    });
  });
}

function playMusic() {
  const audio = $("#backgroundMusic");
  audio.play().then(() => { musicPlaying = true; updateMusicButtons(); }).catch(() => { musicPlaying = false; });
}

function toggleMusic() {
  const audio = $("#backgroundMusic");
  if (audio.paused) playMusic();
  else { audio.pause(); musicPlaying = false; updateMusicButtons(); }
}

function updateMusicButtons() {
  const buttons = $$("#musicToggleMain");
  buttons.forEach((button) => {
    const status = button.querySelector(".music-switch-status");
    const thumb = button.querySelector(".music-toggle-thumb");
    button.classList.toggle("is-on", musicPlaying);
    if (status) status.textContent = musicPlaying ? "ON" : "OFF";
    if (thumb) thumb.style.transform = musicPlaying ? "translateX(17px)" : "translateX(0)";
    button.setAttribute("aria-pressed", String(musicPlaying));
    button.setAttribute("aria-label", musicPlaying ? getTranslation("musicOn") : getTranslation("musicOff"));
    button.title = musicPlaying ? getTranslation("musicOn") : getTranslation("musicOff");
  });
}

function setupMusic() {
  $$("#musicToggleMain").forEach((button) => {
    button.addEventListener("click", (event) => { event.stopPropagation(); toggleMusic(); });
  });
  updateMusicButtons();
}

