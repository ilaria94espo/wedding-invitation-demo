let currentLanguage = localStorage.getItem("eventLanguage") || "it";
let musicPlaying = false;
const GALLERY_SESSION_KEY = "eventGallerySessionUploads";
let sessionGalleryUploads = new Set();
try {
  sessionGalleryUploads = new Set(JSON.parse(sessionStorage.getItem(GALLERY_SESSION_KEY) || "[]"));
} catch (_) {}

function saveSessionGalleryUploads() {
  try { sessionStorage.setItem(GALLERY_SESSION_KEY, JSON.stringify([...sessionGalleryUploads])); } catch (_) {}
}
const $ = (selector) => document.querySelector(selector);
const $$ = (selector) => [...document.querySelectorAll(selector)];

function getTranslation(key) {
  const base = (typeof TRANSLATIONS !== "undefined" && TRANSLATIONS[currentLanguage]) || {};
  return TOPIC_TRANSLATIONS[currentLanguage]?.[key] ?? base[key] ?? key;
}

function applySectionVisibility() {
  const flags = EVENT.sections || {};
  $$('[data-section-flag]').forEach((el) => {
    el.hidden = flags[el.dataset.sectionFlag] === false;
  });
}

function applyTranslations() {
  document.documentElement.lang = currentLanguage;
  $$('[data-i18n]').forEach((el) => {
    el.textContent = getTranslation(el.dataset.i18n);
  });
  $$('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', getTranslation(el.dataset.i18nAria));
  });
  const languageButton = $("#languageButton");
  if (languageButton) languageButton.textContent = currentLanguage.toUpperCase();
}

function formatEventDate() {
  return EVENT.date.display[currentLanguage] || EVENT.date.display.it;
}

function applyEventData() {
  document.title = `${EVENT.couple.names} — ${formatEventDate()}`;
  $("#welcomeNames").textContent = EVENT.couple.names;
  $("#welcomeDate").textContent = formatEventDate();
  $("#footerDate").textContent = formatEventDate();
  $("#coupleImage").src = EVENT.images.couple;
  $("#landscapeImage").src = EVENT.images.landscape;
  $("#ceremonyText").innerHTML = `<strong>${EVENT.ceremony.venue}</strong><br>${EVENT.ceremony.address}`;
  $("#receptionText").innerHTML = `<strong>${EVENT.reception.venue}</strong><br>${EVENT.reception.address}`;
  $("#ceremonyMap").href = EVENT.ceremony.mapsUrl;
  $("#receptionMap").href = EVENT.reception.mapsUrl;
  $("#emailLink").href = `mailto:${EVENT.contact.email}`;
  $("#emailLink").textContent = EVENT.contact.email;
  $("#phoneLink").href = `tel:${EVENT.contact.phone.replace(/\s+/g, "")}`;
  $("#phoneLink").textContent = EVENT.contact.phone;
  document.documentElement.style.setProperty("--primary", EVENT.theme.primary);
  document.documentElement.style.setProperty("--secondary", EVENT.theme.secondary);
  document.documentElement.style.setProperty("--accent", EVENT.theme.accent);
  document.documentElement.style.setProperty("--background", EVENT.theme.background);
  document.documentElement.style.setProperty("--paper", EVENT.theme.paper);
  document.documentElement.style.setProperty("--text", EVENT.theme.text);
  buildGallery(EVENT.gallery.map((src) => ({ name: src, url: src })));
}

function startCountdown() {
  const target = new Date(EVENT.date.iso).getTime();
  function update() {
    const distance = Math.max(0, target - Date.now());
    $("#days").textContent = String(Math.floor(distance / 86400000)).padStart(2, "0");
    $("#hours").textContent = String(Math.floor((distance % 86400000) / 3600000)).padStart(2, "0");
    $("#minutes").textContent = String(Math.floor((distance % 3600000) / 60000)).padStart(2, "0");
    $("#seconds").textContent = String(Math.floor((distance % 60000) / 1000)).padStart(2, "0");
  }
  update();
  setInterval(update, 1000);
}

let invitationOpened = false;

function openInvitation() {
  if (invitationOpened) return;
  invitationOpened = true;
  const opening = $("#opening");
  const site = $("#site");
  if (!opening || !site) return;

  opening.classList.add("is-open");
  setTimeout(() => {
    site.classList.remove("hidden");
    opening.classList.add("closing");
    document.body.classList.add("no-scroll");

    setTimeout(() => {
      opening.remove();
      showLanguageModal();
    }, 850);
  }, 700);
}

function showLanguageModal() {
  const modal = $("#languageModal");
  if (!modal) return;
  modal.classList.remove("hidden");
  modal.hidden = false;
  modal.setAttribute("aria-hidden", "false");
  modal.style.display = "grid";
  document.body.classList.add("no-scroll");
}

function chooseLanguage(lang) {
  const supported = ["it", "en", "de", "fr", "es"];
  if (!supported.includes(lang)) return;

  currentLanguage = lang;
  try { localStorage.setItem("eventLanguage", lang); } catch (_) {}

  // Apply only synchronous UI changes first. Never let optional code block entry.
  try { applyTranslations(); } catch (error) { console.warn("Translations:", error); }
  try { applyEventData(); } catch (error) { console.warn("Event data:", error); }
  try { applySectionVisibility(); } catch (error) { console.warn("Sections:", error); }

  const modal = document.getElementById("languageModal");
  const site = document.getElementById("site");

  // Explicitly show the invitation and explicitly hide the language overlay.
  if (site) {
    site.classList.remove("hidden");
    site.hidden = false;
    site.style.display = "block";
  }
  if (modal) {
    modal.classList.add("hidden");
    modal.hidden = true;
    modal.style.display = "none";
    modal.setAttribute("aria-hidden", "true");
  }
  document.body.classList.remove("no-scroll");

  try { playMusic(); } catch (_) {}
}

// Expose this function globally so the language buttons can call it directly.
window.chooseLanguage = chooseLanguage;

function setupLanguageMenu() {
  const button = $("#languageButton");
  const dropdown = $("#languageDropdown");
  if (!button || !dropdown) return;
  button.addEventListener("click", (event) => {
    event.stopPropagation();
    const open = dropdown.classList.toggle("open");
    button.setAttribute("aria-expanded", String(open));
  });
  $$('[data-lang]').forEach((item) => item.addEventListener("click", (event) => {
    event.preventDefault();
    event.stopPropagation();
    chooseLanguage(item.dataset.lang);
    dropdown.classList.remove("open");
    button.setAttribute("aria-expanded", "false");
  }));
  document.addEventListener("click", (event) => {
    if (!event.target.closest(".language-corner")) {
      dropdown.classList.remove("open");
      button.setAttribute("aria-expanded", "false");
    }
  });
}

function setupLanguageModal() {
  // One delegated listener, attached independently of the rest of the app.
  document.addEventListener("click", (event) => {
    const button = event.target.closest("[data-choice-lang]");
    if (!button) return;
    event.preventDefault();
    event.stopImmediatePropagation();
    chooseLanguage(button.getAttribute("data-choice-lang"));
  }, true);
}

function playMusic() {
  const audio = $("#backgroundMusic");
  audio.play().then(() => { musicPlaying = true; updateMusicButtons(); }).catch(() => { musicPlaying = false; });
}

function toggleMusic() {
  const audio = $("#backgroundMusic");
  if (audio.paused) playMusic();
  else { audio.pause(); musicPlaying = false; updateMusicButtons(); }
}

function updateMusicButtons() {
  const button = $("#musicToggleIntro");
  if (button) button.textContent = musicPlaying ? "♫" : "♪";
}

function setupMusic() {
  const button = $("#musicToggleIntro");
  if (button) button.addEventListener("click", (event) => { event.stopPropagation(); toggleMusic(); });
}

async function loadPublicGallery() {
  const grid = $("#galleryGrid");
  if (!grid || typeof supabaseClient === "undefined") return;

  try {
    // Uploaded photos are stored directly inside the event folder.
    const { data, error } = await supabaseClient.storage
      .from("event-gallery")
      .list(EVENT.id, { limit: 100, sortBy: { column: "name", order: "asc" } });

    if (error) throw error;

    const files = (data || []).filter((file) => {
      const name = String(file.name || "");
      return name && !name.endsWith("/") && /\.(jpe?g|png|webp)$/i.test(name);
    });

    const uploaded = files.map((file) => ({
      name: file.name,
      path: `${EVENT.id}/${file.name}`,
      url: supabaseClient.storage
        .from("event-gallery")
        .getPublicUrl(`${EVENT.id}/${file.name}`).data.publicUrl
    }));

    const staticPhotos = (EVENT.gallery || []).map((src) => ({ name: src, url: src }));
    buildGallery([...staticPhotos, ...uploaded]);
  } catch (error) {
    console.warn("Public gallery could not be loaded:", error);
    // Keep any configured/static gallery photos visible even if listing is unavailable.
    buildGallery((EVENT.gallery || []).map((src) => ({ name: src, url: src })));
  }
}

function buildGallery(items) {
  const grid = $("#galleryGrid");
  if (!grid) return;
  grid.innerHTML = "";
  items.forEach((item, index) => {
    const wrapper = document.createElement("div");
    wrapper.className = "gallery-item";

    const button = document.createElement("button");
    button.type = "button";
    button.className = "gallery-photo-button";
    button.setAttribute("aria-label", `Photo ${index + 1}`);
    const img = document.createElement("img");
    img.src = item.url;
    img.alt = `${EVENT.couple.names} — photo ${index + 1}`;
    button.appendChild(img);
    button.addEventListener("click", () => openLightbox(item.url));
    wrapper.appendChild(button);

    // Delete is available only for photos uploaded during this browser session.
    if (item.path && sessionGalleryUploads.has(item.path)) {
      const deleteButton = document.createElement("button");
      deleteButton.type = "button";
      deleteButton.className = "gallery-delete-button";
      deleteButton.textContent = "🗑";
      deleteButton.title = getTranslation("galleryDelete");
      deleteButton.setAttribute("aria-label", getTranslation("galleryDelete"));
      deleteButton.addEventListener("click", (event) => {
        event.stopPropagation();
        deleteSessionGalleryPhoto(item.path, wrapper);
      });
      wrapper.appendChild(deleteButton);
    }

    grid.appendChild(wrapper);
  });
}

async function ensureAnonymousSession() {
  if (typeof supabaseClient === "undefined") throw new Error("Supabase is not available");

  const { data: existing, error: getError } = await supabaseClient.auth.getSession();
  if (getError) throw getError;
  if (existing?.session?.user) return existing.session;

  const { data, error } = await supabaseClient.auth.signInAnonymously();
  if (error) throw error;
  if (!data?.session?.user) throw new Error("Anonymous session could not be created");
  return data.session;
}

async function deleteSessionGalleryPhoto(path, wrapper) {
  if (!path || typeof supabaseClient === "undefined") return;
  if (!sessionGalleryUploads.has(path)) return;
  const confirmed = window.confirm(getTranslation("galleryDeleteConfirm"));
  if (!confirmed) return;

  const deleteButton = wrapper.querySelector(".gallery-delete-button");
  if (deleteButton) { deleteButton.disabled = true; deleteButton.textContent = "…"; }

  try {
    await ensureAnonymousSession();
    const { error } = await supabaseClient.storage
      .from("event-gallery")
      .remove([path]);
    if (error) throw error;

    sessionGalleryUploads.delete(path);
    saveSessionGalleryUploads();
    wrapper.remove();
    const message = $("#publicGalleryMessage");
    if (message) message.textContent = getTranslation("galleryDeleteSuccess");
  } catch (error) {
    console.error("Public gallery delete failed:", error);
    if (deleteButton) { deleteButton.disabled = false; deleteButton.textContent = "🗑"; }
    const message = $("#publicGalleryMessage");
    if (message) message.textContent = getTranslation("galleryDeleteError");
  }
}

async function uploadPublicGallery() {
  const input = $("#publicGalleryFiles");
  const button = $("#publicGalleryUploadButton");
  const message = $("#publicGalleryMessage");
  const files = [...(input.files || [])];
  if (!files.length) { message.textContent = getTranslation("galleryUploadEmpty"); return; }
  if (files.some((file) => file.size > 10 * 1024 * 1024)) { message.textContent = getTranslation("galleryUploadSize"); return; }
  button.disabled = true;
  message.textContent = getTranslation("galleryUploadSending");
  try {
    // The anonymous Supabase account gives every visitor a private owner_id
    // on Storage objects. This lets Supabase authorize deletion of only the
    // photos uploaded by that visitor, without asking for a login.
    await ensureAnonymousSession();

    for (const file of files) {
      const safeName = file.name.toLowerCase().replace(/[^a-z0-9._-]+/g, "-");
      const path = `${EVENT.id}/${Date.now()}-${crypto.randomUUID()}-${safeName}`;
      const { error } = await supabaseClient.storage.from("event-gallery").upload(path, file, { contentType: file.type, upsert: false });
      if (error) throw error;
      sessionGalleryUploads.add(path);
    }
    saveSessionGalleryUploads();
    input.value = "";
    await loadPublicGallery();
    message.textContent = getTranslation("galleryUploadSuccess");
  } catch (error) {
    console.error("Public gallery upload failed:", error);
    message.textContent = getTranslation("galleryUploadError");
  } finally { button.disabled = false; }
}

function setupGalleryUpload() {
  const input = $("#publicGalleryFiles");
  const button = $("#publicGalleryUploadButton");
  const box = $(".gallery-upload-box");
  if (!input || !button) return;
  box.addEventListener("click", () => input.click());
  button.addEventListener("click", uploadPublicGallery);
  input.addEventListener("change", () => {
    if (input.files.length) $("#publicGalleryMessage").textContent = `${input.files.length} ${currentLanguage === "it" ? "foto selezionate" : "photos selected"}`;
  });
}

function setupRsvp() {
  const form = $("#rsvp");
  if (!form) return;
  const submitButton = form.querySelector('button[type="submit"]');
  const message = $("#rsvpMessage");
  form.addEventListener("submit", async (event) => {
    event.preventDefault();
    const data = new FormData(form);
    const name = String(data.get("name") || "").trim();
    const attending = data.get("attending") === "yes";
    const guests = Number.parseInt(data.get("guests"), 10);
    const dietary = String(data.get("dietary") || "").trim();
    if (!name) { message.textContent = getTranslation("rsvpError"); return; }
    if (!Number.isInteger(guests) || guests < 1 || guests > 10) { message.textContent = getTranslation("rsvpGuestsError"); return; }
    submitButton.disabled = true; message.textContent = getTranslation("rsvpSending");
    try {
      const { error } = await supabaseClient.from("rsvps").insert({ event_id: EVENT.id, name, attending, guests: attending ? guests : 0, dietary: dietary || null });
      if (error) throw error;
      message.textContent = getTranslation("rsvpSuccess").replace("{name}", name);
      form.reset(); form.querySelector('[name="guests"]').value = "1";
    } catch (error) { console.error(error); message.textContent = getTranslation("rsvpError"); }
    finally { submitButton.disabled = false; }
  });
}

function openLightbox(src) { $("#lightboxImage").src = src; $("#lightbox").classList.remove("hidden"); document.body.classList.add("no-scroll"); }
function closeLightbox() { $("#lightbox").classList.add("hidden"); document.body.classList.remove("no-scroll"); }
function setupLightbox() {
  $("#lightboxClose").addEventListener("click", closeLightbox);
  $("#lightbox").addEventListener("click", (event) => { if (event.target.id === "lightbox") closeLightbox(); });
}

document.addEventListener("DOMContentLoaded", () => {
  document.body.classList.add("no-scroll");

  // Envelope and language controls are initialized first and independently.
  const seal = $("#openInvitationSeal");
  if (seal) seal.addEventListener("click", openInvitation);
  setupLanguageModal();

  // Optional components are isolated so one failure can never stop the invitation.
  const safe = (name, fn) => {
    try { fn(); } catch (error) { console.error(name, error); }
  };
  safe("translations", applyTranslations);
  safe("event data", applyEventData);
  safe("section visibility", applySectionVisibility);
  safe("countdown", startCountdown);
  safe("language menu", setupLanguageMenu);
  safe("RSVP", setupRsvp);
  safe("gallery upload", setupGalleryUpload);
  safe("lightbox", setupLightbox);
  safe("music", setupMusic);

  loadPublicGallery().catch((error) => console.warn("Gallery:", error));
  if (window.lucide) safe("icons", () => lucide.createIcons());
});
