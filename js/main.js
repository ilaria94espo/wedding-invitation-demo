function chooseLanguage(lang) {
  const supported = ["it", "en", "de", "fr", "es"];
  if (!supported.includes(lang)) return;

  currentLanguage = lang;
  try { localStorage.setItem("eventLanguage", lang); } catch (_) {}

  // Apply only synchronous UI changes first. Never let optional code block entry.
  try { applyTranslations(); } catch (error) { console.warn("Translations:", error); }
  try { applyEventData(); } catch (error) { console.warn("Event data:", error); }
  try { applySectionVisibility(); } catch (error) { console.warn("Sections:", error); }

  const modal = document.getElementById("languageModal");
  const site = document.getElementById("site");

  // Explicitly show the invitation and explicitly hide the language overlay.
  if (site) {
    site.classList.remove("hidden");
    site.hidden = false;
    site.style.display = "block";
  }
  if (modal) {
    modal.classList.add("hidden");
    modal.hidden = true;
    modal.style.display = "none";
    modal.setAttribute("aria-hidden", "true");
  }
  document.body.classList.remove("no-scroll");

}

